// ----- 基本の型
type 文字 = string
type 円 = number                 // 整数
type 数 = number
type 日付 = string               // YYYY-MM-DD
type 顧客ID = string
type 注文ID = string
type 商品コード = string         // 商品マスタのコード
type 都道府県 = '北海道' | '青森県' | '岩手県' | '宮城県' | '秋田県' | '山形県' | '福島県' | '茨城県' | '栃木県' | '群馬県' | '埼玉県' | '千葉県' | '東京都' // 例なので途中まで

// ===== 顧客（root）: 注文する人
type 顧客 = {
  顧客ID: 顧客ID              // PK
  名前: 文字
  住所: 住所
}
type 住所 = {
  都道府県: 都道府県
  残り: 文字                  // 市区町村以下
}

// ===== 注文（root）: 1回の購入。明細と支払いを持つ
type 注文 = {
  注文ID: 注文ID              // PK
  顧客: 顧客ID                // FK
  注文日: 日付
  明細: 明細[]
  支払い: 支払い
  状態: '受付' | '発送済み' | 'キャンセル'
}
type 明細 = {
  商品: 商品コード            // FK
  数量: 数
  単価: 円                    // 注文時点の価格
}
type 支払い = カード払い | 振込
type カード払い = {
  方法: 'カード'
  承認番号: 文字
}
type 振込 = {
  方法: '振込'
  入金日?: 日付               // 入金前は空
}
// 守ること: 明細は1件以上。キャンセル後は明細を変えない

// ===== 返品（root・★案）: 注文の一部を戻す
type 返品 = {
  注文: 注文ID                // PK・FK
  受付日: 日付                // PK
  理由?: 文字
}
