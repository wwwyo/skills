#!/usr/bin/env python3
"""design.md の token からアプリの oxlint 設定を生成する。

lint-setup.py <design.md> [--out DIR] [--component-glob GLOB ...] [--tailwind] [--tailwind-entry PATH]
              [--check] [--dry-run] [--json]

生成物（--out、既定は design.md と同じ dir）:
- oxlint.design-md.json: アプリの .oxlintrc.json から extends する設定
- oxlint-plugin-design-md.mjs: JSX の style 属性で token 以外の値（色・余白・文字・radius 等）を禁止する JS plugin
- --tailwind 時のみ design-md.theme.css: design.md の token を Tailwind v4 の utility にする `@theme`。
  oxlint 設定には eslint-plugin-better-tailwindcss で未登録 class・任意値・Tailwind 既定の色と scale の禁止を足す

component（既定 `**/components/**`）は制約の対象外。生成物は design.md の派生物（format の `## Exports`）。
冒頭の marker 行が無い既存ファイルは上書きしない。--check は生成物が design.md と一致しているかだけを見て、ずれていれば exit 1。
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

from check_common import CUSTOM_PROP_DEF_RE, spec_text, strip_comments

MARKER = "generated by design-md lint-setup"
CONFIG_FILE = "oxlint.design-md.json"
PLUGIN_FILE = "oxlint-plugin-design-md.mjs"
THEME_FILE = "design-md.theme.css"
DEFAULT_COMPONENT_GLOBS = ["**/components/**"]

CATEGORIES = ("color", "font-family", "font-size", "line-height", "letter-spacing", "space", "radius", "shadow", "ease", "duration")

COLOR_FUNCS = ("rgb", "rgba", "hsl", "hsla", "hwb", "lab", "lch", "oklab", "oklch", "color")
COLOR_VALUE_RE = re.compile(r"^(#[0-9a-fA-F]{3,8}|(?:%s)\(.*\)|color-mix\(.*\)|transparent|white|black)$" % "|".join(COLOR_FUNCS))
LENGTH_RE = re.compile(r"^-?[\d.]+(px|rem|em|%|vw|vh|ch|ex)?$|^calc\(.*\)$|^clamp\(.*\)$|^min\(.*\)$|^max\(.*\)$")
DURATION_RE = re.compile(r"^[\d.]+m?s$")
VAR_ONLY_RE = re.compile(r"^var\(\s*(--[\w-]+)\s*(?:,.*)?\)$")
SHADCN_COLORS = {
    "background", "foreground", "card", "card-foreground", "popover", "popover-foreground",
    "primary", "primary-foreground", "secondary", "secondary-foreground", "muted", "muted-foreground",
    "accent", "accent-foreground", "destructive", "destructive-foreground", "border", "input", "ring",
}

# style の property → 許す token category。値は token の var() と下の keyword だけになる
PROPERTY_CATEGORIES = {
    "color": "color", "background-color": "color", "border-color": "color", "outline-color": "color",
    "text-decoration-color": "color", "fill": "color", "stroke": "color", "caret-color": "color",
    "accent-color": "color", "column-rule-color": "color",
    "border-top-color": "color", "border-right-color": "color", "border-bottom-color": "color", "border-left-color": "color",
    "font-family": "font-family", "font-size": "font-size", "line-height": "line-height",
    "letter-spacing": "letter-spacing", "border-radius": "radius", "box-shadow": "shadow",
    "transition-timing-function": "ease", "animation-timing-function": "ease",
    "transition-duration": "duration", "animation-duration": "duration",
}
SPACE_PROPERTIES = ("margin", "margin-top", "margin-right", "margin-bottom", "margin-left", "margin-inline", "margin-block",
                    "padding", "padding-top", "padding-right", "padding-bottom", "padding-left", "padding-inline", "padding-block",
                    "gap", "row-gap", "column-gap")
REPEATABLE = {"radius": "space", "shadow": "comma", "ease": "comma", "duration": "comma"}
GLOBAL_KEYWORDS = ("inherit", "initial", "unset", "revert")
CATEGORY_KEYWORDS = {
    "color": ("transparent", "currentColor", "currentcolor"),
    "line-height": ("normal", "1"),
    "letter-spacing": ("normal", "0"),
    "radius": ("0", "9999px", "50%"),
    "shadow": ("none",),
    "ease": ("linear",),
    "duration": ("0s",),
}
# Tailwind v4 の theme namespace（https://tailwindcss.com/docs/theme#theme-variable-namespaces）
TAILWIND_NAMESPACES = {
    "color": "color", "font-family": "font", "font-size": "text", "line-height": "leading",
    "letter-spacing": "tracking", "space": "spacing", "radius": "radius", "shadow": "shadow", "ease": "ease",
}
NAME_PREFIXES = ("font-family-", "font-size-", "line-height-", "letter-spacing-", "font-", "text-", "leading-",
                 "tracking-", "spacing-", "space-", "radius-", "shadow-", "ease-", "easing-", "duration-", "color-")


def parse_tokens(design_md: Path) -> dict[str, str]:
    """design.md の css block から `--name: value` を出現順に返す（同名は先勝ち＝:root の値）。"""
    css = strip_comments(spec_text(design_md))
    tokens: dict[str, str] = {}
    for m in CUSTOM_PROP_DEF_RE.finditer(css):
        tokens.setdefault(m.group(1), m.group(2).strip())
    return tokens


def classify(name: str, value: str, tokens: dict[str, str], _seen: frozenset[str] = frozenset()) -> str | None:
    """token を category に振り分ける。名前で決まるものは名前、決まらなければ値で判定する。"""
    bare = name[2:]
    v = value.strip()
    if re.search(r"(^|-)(font-size|text)(-|$)", bare) and not COLOR_VALUE_RE.match(v):
        return "font-size"
    if re.search(r"(^|-)(line-height|leading)(-|$)", bare):
        return "line-height"
    if re.search(r"(^|-)(letter-spacing|tracking)(-|$)", bare):
        return "letter-spacing"
    if re.search(r"(^|-)(font-family|font)(-|$)", bare):
        return None if re.search(r"weight", bare) else "font-family"
    if re.search(r"(^|-)radius(-|$)", bare):
        return "radius"
    if re.search(r"(^|-)shadow(-|$)", bare):
        return "shadow"
    if re.search(r"(^|-)(ease|easing)(-|$)", bare):
        return "ease"
    if re.search(r"(^|-)duration(-|$)", bare) or DURATION_RE.match(v):
        return "duration"
    if re.search(r"(^|-)(space|spacing|gap)(-|$)", bare) and LENGTH_RE.match(v):
        return "space"
    if bare in SHADCN_COLORS or COLOR_VALUE_RE.match(v):
        return "color"
    m = VAR_ONLY_RE.match(v)
    if m and m.group(1) in tokens and m.group(1) not in _seen:
        return classify(m.group(1), tokens[m.group(1)], tokens, _seen | {name})
    return None


def group_tokens(tokens: dict[str, str]) -> dict[str, list[str]]:
    groups: dict[str, list[str]] = {c: [] for c in CATEGORIES}
    for name, value in tokens.items():
        cat = classify(name, value, tokens)
        if cat:
            groups[cat].append(name)
    return groups


def tailwind_name(name: str) -> str:
    bare = name[2:]
    for p in NAME_PREFIXES:
        if bare.startswith(p) and len(bare) > len(p):
            return bare[len(p):]
    return bare


def theme_css(groups: dict[str, list[str]], header: str) -> str:
    lines = [
        f"/* {header} */",
        "/* design.md の token を Tailwind の utility にする（bg-primary・p-sm 等）。entry CSS で @import \"tailwindcss\" の後に読む。",
        "   既定の theme は残す（component は既定の値を使ってよい）。component 以外での既定値の使用は oxlint が止める */",
        "@theme inline reference {",
    ]
    for cat, ns in TAILWIND_NAMESPACES.items():
        for n in groups[cat]:
            short = tailwind_name(n)
            lines.append(f"  --{ns}: var({n});" if cat == "radius" and short == "radius" else f"  --{ns}-{short}: var({n});")
    lines.append("}")
    return "\n".join(lines) + "\n"


ARBITRARY_PATTERN = (
    r"^(?:[\w-]+:)*!?-?(?:bg|text|border(?:-[trblxyse])?|ring|outline|fill|stroke|from|via|to|shadow|decoration|accent|caret|divide|placeholder"
    r"|p[trblxyse]?|m[trblxyse]?|gap(?:-[xy])?|space-[xy]|inset(?:-[xy])?|top|right|bottom|left|rounded(?:-[\w]+)?|font|leading|tracking"
    r"|duration|ease|delay)-\[.+\]!?$"
)
VARIANTS = r"^(?:[\w-]+:)*!?-?"
COLOR_UTILS = r"(?:bg|text|border(?:-[trblxyse])?|ring|ring-offset|outline|fill|stroke|from|via|to|shadow|decoration|accent|caret|divide|placeholder|inset-shadow|inset-ring)"
TAILWIND_PALETTE = ("red", "orange", "amber", "yellow", "lime", "green", "emerald", "teal", "cyan", "sky", "blue", "indigo",
                    "violet", "purple", "fuchsia", "pink", "rose", "slate", "gray", "zinc", "neutral", "stone", "mauve",
                    "olive", "mist", "taupe", "black", "white")
# token の category ごとに、Tailwind 既定の scale を使う class（design.md の token を迂回する）
DEFAULT_SCALES = {
    "font-size": (r"text", ("xs", "sm", "base", "lg", "xl", "2xl", "3xl", "4xl", "5xl", "6xl", "7xl", "8xl", "9xl")),
    "font-family": (r"font", ("sans", "serif", "mono")),
    "line-height": (r"leading", ("none", "tight", "snug", "normal", "relaxed", "loose", r"\d+(?:\.\d+)?")),
    "letter-spacing": (r"tracking", ("tighter", "tight", "normal", "wide", "wider", "widest")),
    "space": (r"(?:p[trblxyse]?|m[trblxyse]?|gap(?:-[xy])?|space-[xy])", (r"\d+(?:\.\d+)?", "px")),
    "radius": (r"rounded(?:-[trblse]{1,2})?", ("xs", "sm", "md", "lg", "xl", "2xl", "3xl", "4xl")),
    "shadow": (r"shadow", ("2xs", "xs", "sm", "md", "lg", "xl", "2xl")),
    "ease": (r"ease", ("in", "out", "in-out")),
}
TOKEN_MESSAGE = "design.md の token を使う（無い値は design.md に token を足してから。component は対象外）"


def restricted_class_patterns(groups: dict[str, list[str]]) -> list[dict]:
    restrict = [{"pattern": ARBITRARY_PATTERN, "message": "$0: 任意値の class は使わない。" + TOKEN_MESSAGE}]
    if groups["color"]:
        tokens = {tailwind_name(n) for n in groups["color"]}
        palette = [c for c in TAILWIND_PALETTE if c not in tokens]
        restrict.append({
            "pattern": VARIANTS + COLOR_UTILS + r"-(?:%s)(?:-\d+)?(?:/\d+)?!?$" % "|".join(palette),
            "message": "$0: Tailwind 既定の色は使わない。" + TOKEN_MESSAGE,
        })
    for cat, (prefix, scale) in DEFAULT_SCALES.items():
        if not groups[cat]:
            continue
        tokens = {tailwind_name(n) for n in groups[cat]}
        values = [v for v in scale if v not in tokens]
        restrict.append({
            "pattern": VARIANTS + prefix + r"-(?:%s)!?$" % "|".join(values),
            "message": "$0: Tailwind 既定の scale は使わない。" + TOKEN_MESSAGE,
        })
    return restrict


def camel(prop: str) -> str:
    return re.sub(r"-(\w)", lambda m: m.group(1).upper(), prop)


def plugin_js(groups: dict[str, list[str]]) -> str:
    """JSX の style 属性を検査する oxlint の JS plugin（ESLint 互換の rule API）。"""
    allowed = {cat: {"tokens": [n[2:] for n in groups[cat]], "keywords": list(CATEGORY_KEYWORDS.get(cat, ()) + (("0", "auto") if cat == "space" else ())), "multi": REPEATABLE.get(cat, "space" if cat == "space" else None)}
               for cat in CATEGORIES if groups[cat]}
    props = {camel(p): c for p, c in PROPERTY_CATEGORIES.items() if groups[c]}
    if groups["space"]:
        props.update({camel(p): "space" for p in SPACE_PROPERTIES})
    color = r"#[0-9a-fA-F]{3,8}\b|\b(?:%s)\(" % "|".join(COLOR_FUNCS)
    return f"""const ALLOWED = {json.dumps(allowed, indent=2)};
const PROPS = {json.dumps(props, indent=2)};
const GLOBAL_KEYWORDS = {json.dumps(list(GLOBAL_KEYWORDS))};
const COLOR_RE = /{color}/;
const MESSAGE = {json.dumps(TOKEN_MESSAGE, ensure_ascii=False)};

function propName(key) {{
  if (key.type === "Identifier") return key.name;
  if (key.type === "Literal" && typeof key.value === "string") return key.value.replace(/-(\\w)/g, (_, c) => c.toUpperCase());
  return null;
}}

function staticValue(node) {{
  if (node.type === "Literal") return String(node.value);
  if (node.type === "TemplateLiteral" && node.expressions.length === 0) return node.quasis[0].value.cooked;
  return null;
}}

function isAllowed(category, value) {{
  const rule = ALLOWED[category];
  const ok = (v) => GLOBAL_KEYWORDS.includes(v) || rule.keywords.includes(v) || rule.tokens.some((t) => v === `var(--${{t}})`);
  const parts = rule.multi === "comma" ? value.split(/\\s*,\\s*/) : rule.multi === "space" ? value.trim().split(/\\s+/) : [value.trim()];
  return parts.length > 0 && parts.every(ok);
}}

const noRawStyle = {{
  meta: {{ type: "problem", docs: {{ description: "JSX の style 属性で design.md の token 以外の値を禁止する" }} }},
  create(context) {{
    return {{
      JSXAttribute(node) {{
        if (node.name.name !== "style" || node.value?.type !== "JSXExpressionContainer") return;
        const obj = node.value.expression;
        if (obj.type !== "ObjectExpression") return;
        for (const p of obj.properties) {{
          if (p.type !== "Property") continue;
          const value = staticValue(p.value);
          if (value === null) continue;
          const name = propName(p.key);
          const category = name && PROPS[name];
          if (category ? !isAllowed(category, value) : COLOR_RE.test(value)) {{
            context.report({{ node: p.value, message: `style の ${{name ?? "?"}}: ${{value}} — ${{MESSAGE}}` }});
          }}
        }}
      }},
    }};
  }},
}};

export default {{ meta: {{ name: "design-md" }}, rules: {{ "no-raw-style": noRawStyle }} }};"""


def oxlint_config(groups: dict[str, list[str]], tailwind: bool, entry: str | None, component_globs: list[str]) -> str:
    rules: dict = {"design-md/no-raw-style": "error"}
    config: dict = {"jsPlugins": [f"./{PLUGIN_FILE}"]}
    if tailwind:
        config["jsPlugins"].append("eslint-plugin-better-tailwindcss")
        # oxlint は extends 先の settings を JS plugin に渡さないので、entryPoint は rule ごとの option で渡す
        tw = {"entryPoint": entry or THEME_FILE}
        rules["better-tailwindcss/no-unknown-classes"] = ["error", tw]
        rules["better-tailwindcss/no-restricted-classes"] = ["error", {**tw, "restrict": restricted_class_patterns(groups)}]
    config["rules"] = rules
    if component_globs:
        config["overrides"] = [{"files": component_globs, "rules": {k: "off" for k in rules if k != "better-tailwindcss/no-unknown-classes"}}]
    return json.dumps(config, ensure_ascii=False, indent=2)


def build_outputs(design_md: Path, out: Path, tailwind: bool, entry: str | None, component_globs: list[str]) -> tuple[dict[Path, str], dict[str, list[str]]]:
    tokens = parse_tokens(design_md)
    groups = group_tokens(tokens)
    rel = Path(design_md.resolve()).relative_to(out.resolve()) if design_md.resolve().is_relative_to(out.resolve()) else design_md.name
    header = f"{MARKER} from {rel}. 直接編集しない — design.md を直して再生成する"
    files: dict[Path, str] = {
        out / CONFIG_FILE: f"// {header}\n" + oxlint_config(groups, tailwind, entry, component_globs) + "\n",
        out / PLUGIN_FILE: f"// {header}\n" + plugin_js(groups) + "\n",
    }
    if tailwind:
        files[out / THEME_FILE] = theme_css(groups, header)
    return files, groups


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description="design.md の token からアプリの oxlint 設定を生成する")
    ap.add_argument("design_md", type=Path)
    ap.add_argument("--out", type=Path, help="生成先 dir（既定: design.md と同じ dir）")
    ap.add_argument("--component-glob", action="append", help="制約から外す component の glob（--out からの相対。既定: **/components/**）")
    ap.add_argument("--tailwind", action="store_true", help="Tailwind v4 の @theme と class の検査も生成する")
    ap.add_argument("--tailwind-entry", help="better-tailwindcss に渡す Tailwind の entry CSS（--out からの相対 path）")
    ap.add_argument("--check", action="store_true", help="書き込まず、生成物が最新でなければ exit 1")
    ap.add_argument("--dry-run", action="store_true", help="書き込まず、変わるファイルを表示する")
    ap.add_argument("--json", action="store_true", help="結果を 1 ファイル 1 行の JSONL で出す")
    args = ap.parse_args(argv)

    if not args.design_md.is_file():
        print(f"error: {args.design_md} が無い", file=sys.stderr)
        return 2
    out = args.out or args.design_md.parent
    if not out.is_dir():
        print(f"error: --out {out} が dir でない", file=sys.stderr)
        return 2
    component_globs = args.component_glob or DEFAULT_COMPONENT_GLOBS
    for p in component_globs + ([args.tailwind_entry] if args.tailwind_entry else []):
        if Path(p).is_absolute() or ".." in Path(p).parts:
            print(f"error: {p} は --out からの相対 path で渡す", file=sys.stderr)
            return 2

    files, groups = build_outputs(args.design_md, out, args.tailwind, args.tailwind_entry, component_globs)
    if not any(groups.values()):
        print("error: design.md の css block に token が見つからない", file=sys.stderr)
        return 2

    results = []
    blocked = stale = False
    for path, content in files.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            action = "unchanged"
        elif current is not None and MARKER not in current.split("\n", 1)[0]:
            action, blocked = "skipped-not-generated", True
        else:
            action = "stale" if args.check else ("would-write" if args.dry_run else ("updated" if current else "created"))
            stale = stale or args.check
            if not (args.check or args.dry_run):
                path.write_text(content, encoding="utf-8")
        results.append({"file": str(path), "action": action})

    summary = {"tokens": {c: len(n) for c, n in groups.items() if n}}
    if args.json:
        for r in results:
            print(json.dumps(r, ensure_ascii=False))
        print(json.dumps({"summary": summary}, ensure_ascii=False))
    else:
        for r in results:
            print(f"{r['action']} {r['file']}")
        print("tokens: " + ", ".join(f"{c}={n}" for c, n in summary["tokens"].items()))
        if blocked:
            print("note: marker の無い既存ファイルは上書きしない。別名に退避するか中身を確認してから消す", file=sys.stderr)
    return 1 if blocked or stale else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
